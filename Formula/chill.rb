  version "0.13.1"
  license "MIT"

  depends_on "deno"
  depends_on "mpv"
  depends_on "ffmpeg"
  depends_on "yt-dlp"

  on_macos do
    on_arm do
      url "https://github.com/willibrandon/chill/releases/download/v#{version}/chill_#{version}_darwin_arm64.tar.gz"
      sha256 "c999dee328a3f1025159790dbd19a263ff7fa2b9fce6f93f453290bbb3a446b0"
